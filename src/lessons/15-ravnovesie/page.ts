import { html, type Mount } from "../../lib/dom";
import { mountTipping } from "./tipping";

export const lesson15: Mount = (el) => {
  const page = html(`
    <article class="lesson">
      <a class="back-link" href="#/">← Всички уроци</a>
      <h1>Равновесие на телата</h1>
      <p>
        Всяко тяло се дърпа надолу от Земята. Можем да си представим, че цялата
        сила на тежестта <i>G</i> е приложена в една точка — <b>центъра на
        тежестта</b> <i>C</i>. От нея зависи дали тялото ще остане да стои,
        или ще се катурне.
      </p>
      <p class="note">
        Кутията стои на гумена подложка — не се плъзга. Може само да се
        преобърне около долния си ръб.
      </p>
      <div data-sim></div>
      <section>
        <h2>Опитай</h2>
        <ol>
          <li>Накланяй рампата бавно и следи пунктирната линия от <i>C</i> надолу.</li>
          <li>Направи товара по-висок. При по-малък или по-голям наклон пада сега?</li>
          <li>Направи основата по-широка. Как се променя ъгълът, при който пада?</li>
        </ol>
      </section>
      <p class="key-idea">
        Пусни въображаема отвесна линия от центъра на тежестта право надолу.
        Докато тя удря <b>вътре</b> в площта, на която тялото стъпва, то стои.
        Щом мине <b>извън</b> тази площ — тялото се преобръща. Затова ниският
        център на тежестта и широката основа правят нещата по-стабилни.
      </p>
    </article>`);
  el.append(page);
  const unmountSim = mountTipping(page.querySelector<HTMLElement>("[data-sim]")!);
  return () => {
    unmountSim();
    page.remove();
  };
};
